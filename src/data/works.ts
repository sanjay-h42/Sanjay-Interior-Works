/**
 * Get all completed projects
 */
export function getAllProjects(): GalleryProject[] {
  return COMPLETED_PROJECTS;
}

/**
 * Get projects filtered by category
 */
export function getProjectsByCategory(category: WorkCategory): GalleryProject[] {
  if (category === 'all') {
    return COMPLETED_PROJECTS;
  }
  if (category === 'pvc-doors') {
    return COMPLETED_PROJECTS.filter(
      (item) => item.category === 'pvc-doors' || item.category === 'picture-pvc-doors'
    );
  }
  return COMPLETED_PROJECTS.filter((item) => item.category === category);
}

/**
 * Get Picture PVC Door projects specifically
 */
export function getPicturePVCDoorProjects(): GalleryProject[] {
  return COMPLETED_PROJECTS.filter(
    (item) => item.category === 'picture-pvc-doors' || item.subCategory === 'picture-doors'
  );
}

/**
 * Get project by ID
 */
export function getProjectById(id: string): GalleryProject | undefined {
  return COMPLETED_PROJECTS.find((item) => item.id === id);
}

/**
 * Count projects in category
 */
export function getProjectCount(category: WorkCategory): number {
  if (category === 'all') {
    return COMPLETED_PROJECTS.length;
  }
  return COMPLETED_PROJECTS.filter((item) => item.category === category).length;
}
